  /// Get kanji for a specific week and day
  static List<KanjiModel> getKanjiByWeekDay(int week, int day) {
    return allKanji.where((k) => k.week == week && k.day == day).toList();
  }

  /// Get all kanji by week
  static List<KanjiModel> getKanjiByWeek(int week) {
    return allKanji.where((k) => k.week == week).toList();
  }

  /// Get kanji by ID
  static KanjiModel? getKanjiById(String id) {
    try {
      return allKanji.firstWhere((k) => k.id == id);
    } catch (e) {
      return null;
    }
  }

  /// Get all kanji
  static List<KanjiModel> getAllKanji() {
    return allKanji;
  }

  /// Search kanji by keyword
  static List<KanjiModel> searchKanji(String query) {
    final lowerQuery = query.toLowerCase();
    return allKanji.where((k) {
      return k.kanji.contains(query) ||
          k.meaning.toLowerCase().contains(lowerQuery) ||
          k.onyomi.toLowerCase().contains(lowerQuery) ||
          k.kunyomi.toLowerCase().contains(lowerQuery);
    }).toList();
  }
